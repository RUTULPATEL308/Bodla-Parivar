const baseUrl = process.env.SUPABASE_URL;
const anonKey = process.env.SUPABASE_ANON_KEY;

if (!baseUrl || !anonKey) {
  console.error(
    'Missing required environment variables. Please set:\n' +
    '  SUPABASE_URL      - Your Supabase project URL\n' +
    '  SUPABASE_ANON_KEY - Your Supabase anon / publishable key'
  );
  process.exit(1);
}

const url = baseUrl + '/rest/v1/offerings';

async function insertTestLabel() {
  try {
    const response = await fetch(url, {
      method: 'POST',
      headers: {
        'apikey': anonKey,
        'Authorization': `Bearer ${anonKey}`,
        'Content-Type': 'application/json',
        'Prefer': 'return=representation'
      },
      body: JSON.stringify({
        // DO NOT send id, it's a UUID generated by Supabase
        title_gu: 'ટેસ્ટિંગ લેબલ - ડેટાબેઝ જોડાયેલ છે',
        title_en: 'TESTING LABEL - DB Connected!',
        description_gu: 'આ માત્ર ડેટાબેઝ કનેક્શન તપાસવા માટે છે.',
        description_en: 'This is just to verify the database connection from both Web and Mobile apps.',
        amount: 101,
        quantity: 1,
        status: 'ACTIVE',
        location_gu: 'ટેસ્ટ લોકેશન',
        location_en: 'Test Location'
      })
    });
    
    if (response.ok) {
      console.log('Successfully inserted testing label!');
      const data = await response.json();
      console.log(data);
    } else {
      console.error('Failed:', response.status, await response.text());
    }
  } catch (err) {
    console.error('Fetch error:', err.message);
  }
}

insertTestLabel();
